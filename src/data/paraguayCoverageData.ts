export function generateParaguaySeedData(count?: number): ZoneDeliveryRecord[] {
  const records: ZoneDeliveryRecord[] = [];
  let counter = 1;

  for (const row of RAW_PARAGUAY_ENTRIES) {
    const isTodos = !row.barrio || row.barrio.toLowerCase() === 'todos';
    const localidadNombre = isTodos ? `${row.ciudad} (Cobertura General)` : row.barrio;
    const calc = calcularFechaEntregaParaguay(row.diasTransito, row.diasEntrega);

    let productosPermitidos: string[] = ['Tridentex (Paraguay)', 'Oxys Serum (Paraguay)', 'Sustarox Gel (Paraguay)'];
    if (row.restriccion.includes('TRIDENTEX')) {
      productosPermitidos = ['Tridentex (Paraguay)'];
    } else if (row.restriccion.includes('OXYS') && row.restriccion.includes('SUSTAROX')) {
      productosPermitidos = ['Oxys Serum (Paraguay)', 'Sustarox Gel (Paraguay)'];
    }

    records.push({
      id: `PY-ZON-${String(counter++).padStart(6, '0')}`,
      campaignId: 'PARAGUAY',
      pais: 'Paraguay',
      region: row.departamento,
      comuna: row.ciudad,
      localidad: localidadNombre,
      departamento: row.departamento,
      ciudad: row.ciudad,
      barrio: row.barrio,
      zipCode: row.zipCode,
      sectorZona: `Sector: ${localidadNombre} (${row.ciudad}, ${row.departamento}${row.zipCode ? ' - CP ' + row.zipCode : ''})`,
      coberturaEstado: 'Factible con Cobertura',
      paqueteria: row.courier,
      metodoPago: 'Efectivo y Transferencia',
      diasTransito: row.diasTransito,
      tiempoEntregaTexto: row.tiempoEntrega,
      diasEntregaTexto: row.diasEntrega,
      fechaEntregaEstimada: calc.fechaTextoLargo,
      costoEnvioPYG: 0,
      envioGratis: true,
      productosDisponibles: productosPermitidos,
      restricciones: row.restriccion !== 'TODOS LOS PRODUCTOS' ? `Restricción: ${row.restriccion}` : undefined,
      observaciones: row.obs || undefined,
      ultimaActualizacion: '2026-10-15'
    });
  }

  // Si se pide mayor cantidad (ej: 1400), expandir por zonas y etapas de reparto
  if (count && count > records.length) {
    const baseList = [...records];
    let cycle = 1;
    while (records.length < count && baseList.length > 0) {
      for (const base of baseList) {
        if (records.length >= count) break;
        const sub = `${base.localidad} - Zona ${cycle + 1}`;
        records.push({
          ...base,
          id: `PY-ZON-${String(counter++).padStart(6, '0')}`,
          localidad: sub,
          sectorZona: `Sector: ${sub} (${base.comuna}, ${base.region})`
        });
      }
      cycle++;
    }
  }

  return records;
}

export function generateParaguayMassiveDataset(targetCount: number = 30000): ZoneDeliveryRecord[] {
  const records: ZoneDeliveryRecord[] = [];
  const base = generateParaguaySeedData();

  let idCounter = 1;
  const copies = Math.ceil(targetCount / base.length);

  for (let c = 0; c < copies; c++) {
    for (const item of base) {
      if (records.length >= targetCount) break;
      const sub = c === 0 ? item.localidad : `${item.localidad} - Sector ${c + 1}`;
      records.push({
        ...item,
        id: `PY-ZON-${String(idCounter++).padStart(6, '0')}`,
        localidad: sub,
        sectorZona: `Sector: ${sub} (${item.comuna})`
      });
    }
  }

  return records;
}
